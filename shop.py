#!/usr/bin/env python3
"""
Signal Shop — spend earned Signal on cosmetic Tidepal goods.

Critical invariant: lifetime Signal NEVER decreases. Tiers, pet growth
stages, and achievements all run on gross lifetime earned (the `rewards`
ledger). The shop spends from a *spendable balance*:

    spendable = gross_lifetime_earned − gross_shop_spent

Every spend is a signed, idempotent, ledger-recorded transaction in
`shop_purchases` (append-only). The price is recorded on the row, so
spendable is always computed server-side — never trusted from a client.

v1 catalog (all cosmetic):
  - 3 accessories (SVG overlays rendered on the pet portrait everywhere):
      acc:sailor_hat (25), acc:star_shades (30), acc:pearl_crown (40)
  - rename_token (20, consumable — renames past the first free one cost one)
  - bypass:<species> (150 — buys a locked species' unlock condition;
      never bypasses one-pet-per-identity)

Anti-gaming: signed endpoints only, server-side balance math, no negative
balances, UNIQUE(fm_id, ref_id) makes double-spends impossible.
"""

import json
import sqlite3
import time

from db import now

SHOP_VERSION = "shop-v1"

# --- catalog ----------------------------------------------------------------
# kind: accessory (one-time, equips to a slot), consumable (repeat-buy),
#       bypass (one-time per locked species).
